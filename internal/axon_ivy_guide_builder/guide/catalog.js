/** The page a walkthrough is listed on first (for links to a walkthrough). */
export function homeOf(walkthrough) {
  for (const part of parts) {
    for (const page of part.pages) if (page.walkthroughs.includes(walkthrough)) return { part, page };
  }
  return null;
}

