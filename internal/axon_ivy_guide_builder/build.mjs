/**
 * Builds the guide into the tutorial project:
 *
 *   runtime/                 →  tutorial/webContent/resources/js/axon-ivy-guide-runtime.min.js
 *   walkthroughs/<n-m>/      →  tutorial/webContent/resources/js/walkthrough-<n-m>.js
 *   guide/                   →  tutorial/webContent/resources/js/axon-ivy-guide.js (with its styles)
 *   vendor/marked.min.js     →  tutorial/webContent/resources/js/marked.min.js (marked 15.0.12, MIT)
 *
 * Everything a browser needs ends up in those files, so the guide works without a network.
 *
 *   node build.mjs            build
 *   node build.mjs --watch    rebuild on change
 *   node build.mjs --check    fail if the committed files are not what the sources produce
 */
import { build, context, transform } from 'esbuild';
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const repo = resolve(root, '../..');
const resources = join(repo, 'tutorial/webContent/resources');
const jsDir = join(resources, 'js');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const args = new Set(process.argv.slice(2));
const generated = ' * Generated by internal/axon_ivy_guide_builder (npm run build) - do not edit.';

/** Walkthrough folders: walkthroughs/<n-m>/index.js → walkthrough-<n-m>.js */
export function walkthroughNames() {
  const dir = join(root, 'walkthroughs');
  return readdirSync(dir).filter(name => statSync(join(dir, name)).isDirectory() && existsSync(join(dir, name, 'index.js'))).sort();
}

/** Stylesheets are imported as (minified) text and injected into the shadow root. */
const cssAsText = {
  name: 'css-as-text',
  setup(b) {
    b.onLoad({ filter: /\.css$/ }, async file => {
      const result = await transform(await readFile(file.path, 'utf8'), { loader: 'css', minify: true });
      return { contents: result.code, loader: 'text' };
    });
  }
};

const shared = {
  bundle: true,
  format: 'iife',
  target: ['es2019'],
  minify: true,
  charset: 'ascii', // no encoding surprises, however the file is served
  legalComments: 'none',
  logLevel: 'warning'
};

function runtimeOptions() {
  return {
    ...shared,
    entryPoints: [join(root, 'runtime/index.js')],
    outfile: join(jsDir, 'axon-ivy-guide-runtime.min.js'),
    plugins: [cssAsText],
    define: { __GUIDE_VERSION__: JSON.stringify(pkg.version) },
    banner: { js: '/*!\n * Axon Ivy Guide - walkthrough runtime ' + pkg.version + '\n' + generated + '\n */' }
  };
}

function walkthroughOptions(name) {
  const dir = join(root, 'walkthroughs', name);
  return {
    ...shared,
    stdin: {
      // works whether this script loads before or after the runtime
      contents: "import definition from './index.js';\n" +
        'if (window.ivyGuide) window.ivyGuide.register(definition.id, definition);\n' +
        'else (window.__ivyGuideQueue = window.__ivyGuideQueue || []).push([definition.id, definition]);\n',
      resolveDir: dir,
      sourcefile: 'register-' + name + '.js'
    },
    // an end page of the project (webContent/view/…/*.html) is shown as it is: imported as text
    loader: { '.html': 'text' },
    outfile: join(jsDir, 'walkthrough-' + name + '.js'),
    banner: { js: '/*!\n * Axon Ivy Guide - walkthrough ' + name.replace('-', '.') + '\n' + generated + '\n * Source: internal/axon_ivy_guide_builder/walkthroughs/' + name + '/\n */' }
  };
}

function guideOptions() {
  return {
    ...shared,
    entryPoints: [join(root, 'guide/index.js')],
    outfile: join(jsDir, 'axon-ivy-guide.js'),
    plugins: [cssAsText],
    banner: { js: '/*!\n * Axon Ivy Guide - the guide page\n' + generated + '\n */' }
  };
}

function inspect(file, text) {
  const problems = [];
  // JSF evaluates #{...} in some resources; make sure a bundle can never contain it.
  if (text.includes('#{')) problems.push('contains "#{", which JSF may treat as an expression');
  if (/[^\x00-\x7f]/.test(text)) problems.push('contains non-ASCII characters');
  if (problems.length) throw new Error(relative(repo, file) + ': ' + problems.join('; '));
}

/** The guide dialog loads one script per walkthrough; the build keeps that list complete. */
const dialogFile = join(repo, 'tutorial/dialog/tutorial/AxonIvyGuide/AxonIvyGuide.xhtml');
function dialogWithWalkthroughs() {
  const xhtml = readFileSync(dialogFile, 'utf8').replace(/\r\n/g, '\n');
  const begin = '<!-- walkthroughs:begin -->';
  const end = '<!-- walkthroughs:end -->';
  const a = xhtml.indexOf(begin);
  const b = xhtml.indexOf(end);
  if (a < 0 || b < a) throw new Error(relative(repo, dialogFile) + ': the markers ' + begin + ' and ' + end + ' are missing');
  const indent = xhtml.slice(xhtml.lastIndexOf('\n', a) + 1, a);
  const lines = walkthroughNames().map(name => indent + '<h:outputScript library="js" name="walkthrough-' + name + '.js" />');
  return xhtml.slice(0, a + begin.length) + '\n' + lines.map(l => l + '\n').join('') + indent + xhtml.slice(b);
}

const ascii = text => text.replace(/[^\x00-\x7f]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
const kb = bytes => (bytes / 1024).toFixed(1).padStart(7) + ' kB';

async function buildAll({ write }) {
  const jobs = [runtimeOptions(), guideOptions(), ...walkthroughNames().map(walkthroughOptions)];
  const outputs = [];
  for (const options of jobs) {
    const result = await build({ ...options, write: false });
    // esbuild escapes non-ASCII text everywhere except in regular expression literals
    const text = ascii(result.outputFiles[0].text);
    inspect(result.outputFiles[0].path, text);
    outputs.push({ path: result.outputFiles[0].path, text });
  }
  outputs.push({ path: join(jsDir, 'marked.min.js'), text: readFileSync(join(root, 'vendor/marked.min.js'), 'utf8').replace(/\r\n/g, '\n') });
  outputs.push({ path: dialogFile, text: dialogWithWalkthroughs() });
  if (write) {
    mkdirSync(jsDir, { recursive: true });
    outputs.forEach(out => writeFileSync(out.path, out.text));
  }
  return outputs;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (args.has('--watch')) {
    const contexts = await Promise.all([runtimeOptions(), guideOptions(), ...walkthroughNames().map(walkthroughOptions)].map(o => context({ ...o, logLevel: 'info' })));
    await Promise.all(contexts.map(c => c.watch()));
    console.log('Watching for changes (the stylesheet is built by "npm run build"). Output: ' + relative(repo, jsDir));
  } else if (args.has('--check')) {
    const outputs = await buildAll({ write: false });
    const stale = outputs.filter(out => !existsSync(out.path) || readFileSync(out.path, 'utf8').replace(/\r\n/g, '\n') !== out.text);
    if (stale.length) {
      console.error('Out of date - run "npm run build":');
      stale.forEach(out => console.error('  ' + relative(repo, out.path)));
      process.exit(1);
    }
    console.log('Up to date: ' + outputs.map(o => relative(resources, o.path)).join(', '));
  } else {
    const outputs = await buildAll({ write: true });
    console.log('Built into ' + relative(repo, resources) + ':');
    outputs.forEach(out => console.log('  ' + kb(Buffer.byteLength(out.text)) + '  ' + relative(resources, out.path)));
  }
}
